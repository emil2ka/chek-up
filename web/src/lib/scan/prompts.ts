export const ENRICH_SYSTEM = `Ты диетолог-аналитик. Для каждой позиции покупки в казахстанском супермаркете оцени добавленный сахар и предложи замену.
Верни JSON строго по схеме, по одному элементу на каждую позицию, i — номер позиции из запроса.
Правила:
- sugar_g — ДОБАВЛЕННЫЙ (свободный) сахар в граммах на всю позицию с учётом объёма/веса и количества: сахар, сиропы, мёд, сахар соков и нектаров. Естественный сахар цельных фруктов, овощей и несладкого молока не считается (0).
- Если у позиции есть «справочник: N г на 100 г/мл», опирайся на это значение.
- junk = true для сладких напитков, энергетиков, соков, сладостей, мороженого, сладкой выпечки, чипсов и снеков.
- Для вредных и очень сладких позиций предложи замену из того же класса товаров, которую реально купить в обычном казахстанском супермаркете (swap_name с объёмом), её примерную цену в тенге (swap_price) и сахар на тот же объём (swap_sugar_g). Замена должна содержать меньше сахара.
- Если замена не нужна — swap_name пустая строка, swap_price 0, swap_sugar_g 0.`;

export function enrichUser(lines: Line[]): string {
  const rows = lines.map((l, i) => {
    const ref = findReference(l.name);
    const hint = ref ? `; справочник: ${ref.label}, ${ref.per100} г на 100 г/мл` : '';
    return `${i}. ${l.name}; кол-во ${l.qty}; ${l.price} ₸${hint}`;
  });
  return `Позиции чека:\n${rows.join('\n')}`;
}
