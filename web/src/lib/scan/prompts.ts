export function enrichUser(lines: Line[]): string {
  const rows = lines.map((l, i) => {
    const ref = findReference(l.name);
    const hint = ref ? `; справочник: ${ref.label}, на 100 г/мл: сахар ${ref.per100} г, соль ${ref.salt100} г, насыщенные жиры ${ref.fat100} г, ${ref.kcal100} ккал` : '';
    return `${i}. ${l.name}; кол-во ${l.qty}; ${l.price} ₸${hint}`;
  });
  return `Позиции чека:\n${rows.join('\n')}`;
}
