  final num g, t, f, k;
  final String? swap, x;
  const CatalogItem({
    required this.id,
    required this.name,
    required this.portion,
    required this.g,
    required this.t,
    required this.f,
    required this.k,
    required this.cat,
    this.swap,
    this.x,
  });

  num valueOf(MetricId m) => switch (m) {
    MetricId.sugar => g,
    MetricId.salt => t,
    MetricId.fat => f,
    MetricId.kcal => k,
  };
}

