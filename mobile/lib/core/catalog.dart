String _norm(String s) => s.toLowerCase().replaceAll('ё', 'е').trim();

/// Поиск по названию и порции; пустой запрос — весь раздел. Сначала то, чего больше всего по выбранному показателю.
List<CatalogItem> searchCatalog(
  String query,
  String cat, [
  MetricId metric = MetricId.sugar,
]) {
  final q = _norm(query);
  final list = catalog
      .where(
        (it) =>
            (cat == 'all' || it.cat == cat) &&
            (q.isEmpty ||
                _norm(it.name).contains(q) ||
                _norm(it.portion).contains(q)),
      )
      .toList();
  final k = metrics[metric]!.cubeG;
  list.sort((a, b) => (b.valueOf(metric) / k).compareTo(a.valueOf(metric) / k));
  return list;
}
